// Generates projects/medra/ui/src/lib/icon/icons/{outline,solid,mini,micro}.ts
// from the SVGs in the `heroicons` package (devDependency, not runtime).
// Re-run whenever the heroicons version is updated.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const heroiconsRoot = join(here, '../../../../node_modules/heroicons');
const iconsOutDir = join(here, '../src/lib/icon/icons');

const variants = [
  { name: 'outline', sourceDir: '24/outline' },
  { name: 'solid', sourceDir: '24/solid' },
  { name: 'mini', sourceDir: '20/solid' },
  { name: 'micro', sourceDir: '16/solid' },
];

function toCamelCase(kebab) {
  return kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function extractInnerMarkup(svg) {
  const match = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!match) {
    throw new Error('SVG without a recognizable <svg>...</svg> tag');
  }
  return match[1].trim().replace(/\s+/g, ' ');
}

for (const variant of variants) {
  const dir = join(heroiconsRoot, variant.sourceDir);
  const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort();

  const entries = files.map((file) => {
    const kebabName = file.replace(/\.svg$/, '');
    const key = toCamelCase(kebabName);
    const markup = extractInnerMarkup(readFileSync(join(dir, file), 'utf8'));
    return { key, kebabName, markup };
  });

  const header = `// AUTO-GENERATED by tools/generate-icons.mjs from the \`heroicons\` package.
// Do not edit by hand — run \`npm run generate:icons\` to regenerate.
`;
  const body = entries
    .map((e) => `export const ${e.key} = \`${e.markup}\`; // ${e.kebabName}`)
    .join('\n');

  writeFileSync(join(iconsOutDir, `${variant.name}.ts`), `${header}\n${body}\n`, 'utf8');
  console.log(`${variant.name}: ${entries.length} icons generated`);
}
